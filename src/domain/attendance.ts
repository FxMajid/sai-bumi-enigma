export function calculateDistanceMeters(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371e3; // Radius bumi dalam meter
  const phi1 = (lat1 * Math.PI) / 180;
  const phi2 = (lat2 * Math.PI) / 180;
  const deltaPhi = ((lat2 - lat1) * Math.PI) / 180;
  const deltaLambda = ((lon2 - lon1) * Math.PI) / 180;

  const a =
    Math.sin(deltaPhi / 2) * Math.sin(deltaPhi / 2) +
    Math.cos(phi1) * Math.cos(phi2) * Math.sin(deltaLambda / 2) * Math.sin(deltaLambda / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));

  return Math.round(R * c);
}

// Map Kelompok to group number
export function mapGroupToNumber(namaKelompok: string): number {
  const norm = namaKelompok.toLowerCase();
  if (norm.includes("team lupin") || norm === "lupin") return 1;
  if (norm.includes("detective lupin") || norm.includes("jubun")) return 2;
  if (norm.includes("conan")) return 3;
  if (norm.includes("holmes")) return 4;
  return 1;
}

